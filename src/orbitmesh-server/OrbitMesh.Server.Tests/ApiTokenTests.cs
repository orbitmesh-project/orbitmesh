        var token = await CreateAsync(api, admin, scopes: [OrbitMeshScope.EdgesRead]);
        var configuration = server.ReadConfigurationFile();
        configuration["OrbitMesh"]!["edges"]!.AsArray().Add(new JsonObject { ["name"] = "edge-by-hand", ["credential"] = token.Name, ["packages"] = new JsonArray() });
        await File.WriteAllTextAsync(Path.Combine(server.ContentRoot, "appsettings.json"), configuration.ToJsonString());
        await ServerFixture.EventuallyAsync(() => server.Options.CurrentValue.Edges.Any(e => e.Name == "edge-by-hand"), "the hand edit should have been reloaded");

        try
        {
            using var response = await api.GetAsync(Doors.OrbitMeshGate, Caller.Key("edge-by-hand", token.Token, "Edge"));

