        Assert.Equal(HttpStatusCode.Forbidden, withOld.StatusCode);
        Assert.Equal(HttpStatusCode.OK, withNew.StatusCode);
        // Its scopes and expiry are what they were.
        var kept = server.Options.CurrentValue.Credentials.Single(c => c.Name == old.Name);
        Assert.Equal(new[] { OrbitMeshScope.EdgesRead, OrbitMeshScope.TelemetryRead }.Order(), kept.Scopes.Order());
        Assert.NotNull(kept.ExpiresUtc);
    }

