            edges.Remove(edges.Single(e => (string?)e!["name"] == "edge-by-hand"));
            await File.WriteAllTextAsync(Path.Combine(server.ContentRoot, "appsettings.json"), cleaned.ToJsonString());
            await ServerFixture.EventuallyAsync(() => server.Options.CurrentValue.Edges.All(e => e.Name != "edge-by-hand"), "the cleanup should have been reloaded");
        }
    }

