    {
        var (api, admin) = await AdminAsync();
        var old = await CreateAsync(api, admin, scopes: [OrbitMeshScope.EdgesRead, OrbitMeshScope.TelemetryRead], expires: DateTimeOffset.UtcNow.AddDays(10));

        using var rotate = await api.PostAsync($"rest/management/credentials/{old.Name}/rotate", Caller.Session(admin));
        var body = JsonNode.Parse(await rotate.Content.ReadAsStringAsync())!;
        var fresh = new Created(old.Name, (string)body["TokenId"]!, (string)body["Token"]!, (string?)body["ExpiresUtc"]);
        await ServerFixture.EventuallyAsync(
            () => server.Options.CurrentValue.Credentials.Single(c => c.Name == old.Name).TokenId == fresh.TokenId,
            "the rotation should have been reloaded");

        Assert.Equal(HttpStatusCode.OK, rotate.StatusCode);
        Assert.Matches(Shape, fresh.Token);
        Assert.NotEqual(old.TokenId, fresh.TokenId);
        using var withOld = await UseAsync(api, old);
