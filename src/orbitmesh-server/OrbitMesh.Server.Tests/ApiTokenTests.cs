/// <summary>The format and the arithmetic of the token, on its own.</summary>
public sealed class ApiTokensUnitTests
{
    private static readonly Regex Shape = new("^omk_[0-9a-f]{16}_[A-Za-z0-9_-]{43}$");

    [Fact]
    public void A_token_has_a_recognisable_prefix_a_public_id_and_a_long_random_secret()
    {
        var token = ApiTokens.Generate();

        Assert.Matches(Shape, token.Token);
        Assert.Equal($"omk_{token.Id}_", token.Token[..21]);
        Assert.True(ApiTokens.TryParse(token.Token, out var id));
        Assert.Equal(token.Id, id);
    }

    [Fact]
    public void Tokens_never_repeat_not_even_their_ids()
    {
        var tokens = Enumerable.Range(0, 500).Select(_ => ApiTokens.Generate()).ToList();

        Assert.Equal(500, tokens.Select(t => t.Token).Distinct().Count());
        Assert.Equal(500, tokens.Select(t => t.Id).Distinct().Count());
    }

    [Fact]
    public void Only_the_hash_is_kept_and_it_verifies_only_the_right_token()
    {
        var token = ApiTokens.Generate();

        Assert.StartsWith("TKN$", token.Stored, StringComparison.Ordinal);
        Assert.DoesNotContain(token.Token, token.Stored, StringComparison.Ordinal);
        Assert.Equal("TKN$" + Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(token.Token))), token.Stored);
        Assert.True(ApiTokens.Verify(token.Stored, token.Token));
        Assert.False(ApiTokens.Verify(token.Stored, token.Token[..^1] + (token.Token[^1] == 'A' ? 'B' : 'A')));
        Assert.False(ApiTokens.Verify(token.Stored, ApiTokens.Generate().Token));
        Assert.False(ApiTokens.Verify(token.Stored, token.Stored));
        Assert.False(ApiTokens.Verify("not a hash", token.Token));
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("omk_")]
    [InlineData("omk_0123456789abcdef_short")]
    [InlineData("omk_0123456789ABCDEF_0123456789012345678901234567890123456789012")] // uppercase id
    [InlineData("omk_0123456789abcdeg_0123456789012345678901234567890123456789012")] // not hex
    [InlineData("omk_0123456789abcdef-0123456789012345678901234567890123456789012")] // wrong separator
    [InlineData("xyz_0123456789abcdef_0123456789012345678901234567890123456789012")] // wrong prefix
    [InlineData("OMK_0123456789abcdef_0123456789012345678901234567890123456789012")] // prefix is case-sensitive
    [InlineData("omk_0123456789abcdef_01234567890123456789012345678901234567890123")] // one too long
    public void Anything_not_shaped_like_a_token_is_not_one(string? presented)
    {
        Assert.False(ApiTokens.TryParse(presented, out _));
    }
}

/// <summary>API tokens end to end: made by the Server, shown once, kept as a hash, scoped, expiring, rotatable,
/// and good for the Console's APIs but never for an Edge or a package.</summary>
public sealed class ApiTokenTests(ServerFixture server) : IClassFixture<ServerFixture>
{
    private static readonly Regex Shape = new("^omk_[0-9a-f]{16}_[A-Za-z0-9_-]{43}$");

    private sealed record Created(string Name, string TokenId, string Token, string? ExpiresUtc);

    private static string UniqueName() => "tok-" + Guid.NewGuid().ToString("N")[..8];

    private async Task<(Api Api, string Admin)> AdminAsync()
    {
        var api = server.CreateApi();
        return (api, await api.SignInAsync(Accounts.Admin.Name, Accounts.Admin.Password));
    }

    private async Task<Created> CreateAsync(Api api, string admin, string? name = null, string[]? scopes = null, DateTimeOffset? expires = null, bool enable = true)
    {
        name ??= UniqueName();
        using var response = await api.PostAsync("rest/management/credentials/tokens", Caller.Session(admin),
            new { Name = name, Scopes = scopes ?? [OrbitMeshScope.EdgesRead], ExpiresUtc = expires, Enable = enable });
        var text = await response.Content.ReadAsStringAsync();
        Assert.True(response.IsSuccessStatusCode, $"Creating '{name}' answered {(int)response.StatusCode}: {text}");
        var body = JsonNode.Parse(text)!;
        await ServerFixture.EventuallyAsync(() => server.Options.CurrentValue.Credentials.Any(c => c.Name == name), "the new token should have been reloaded");
        return new Created((string)body["Name"]!, (string)body["TokenId"]!, (string)body["Token"]!, (string?)body["ExpiresUtc"]);
    }

    private Task<HttpResponseMessage> UseAsync(Api api, Created token, string door = Doors.Management, string path = Doors.ManagementGate) =>
        api.GetAsync(path, Caller.Key(door, token.Token));

    // --- Creation: generated by the Server, shown once, kept as a hash.

    [Fact]
    public async Task A_new_token_is_generated_by_the_server_and_returned_once()
    {
        var (api, admin) = await AdminAsync();

        var token = await CreateAsync(api, admin);

        Assert.Matches(Shape, token.Token);
        Assert.Equal(token.Token[4..20], token.TokenId);
        using var use = await UseAsync(api, token);
        Assert.Equal(HttpStatusCode.OK, use.StatusCode);
    }

    [Fact]
    public async Task Only_a_hash_of_the_token_is_stored_and_nothing_ever_shows_it_again()
    {
        var (api, admin) = await AdminAsync();
        var token = await CreateAsync(api, admin);

        var file = await File.ReadAllTextAsync(Path.Combine(server.ContentRoot, "appsettings.json"));
        using var list = await api.GetAsync("rest/management/credentials?includeAccessKeys=true", Caller.Session(admin));
        using var configuration = await api.GetAsync("rest/management/configuration", Caller.Session(admin));

        var stored = (string)server.ReadConfigurationFile()["OrbitMesh"]!["credentials"]!.AsArray().Single(c => (string?)c!["name"] == token.Name)!["accessKey"]!;
        Assert.Equal(ApiTokens.Hash(token.Token), stored);
        var secret = token.Token[21..];
        foreach (var text in new[] { file, await list.Content.ReadAsStringAsync(), await configuration.Content.ReadAsStringAsync() })
        {
            Assert.DoesNotContain(token.Token, text, StringComparison.Ordinal);
            Assert.DoesNotContain(secret, text, StringComparison.Ordinal);
        }
        var listed = JsonNode.Parse(await list.Content.ReadAsStringAsync())!.AsArray().Single(c => (string?)c!["Name"] == token.Name)!;
        Assert.Equal(token.TokenId, (string?)listed["TokenId"]);
        Assert.Equal("Token", (string?)listed["Kind"]);
        var configured = JsonNode.Parse(await configuration.Content.ReadAsStringAsync())!["credentials"]!.AsArray().Single(c => (string?)c!["name"] == token.Name)!;
        Assert.Equal("********", (string?)configured["accessKey"]);
    }

