        // A token's secret can't be set by editing it.
        Assert.Equal(HttpStatusCode.BadRequest, await SaveRawAsync(new { Name = token.Name, AccessKey = "x", Kind = "Token", Enable = true, Scopes = new[] { "edges:read" } }));
