    private async Task SaveAsync(Api api, string admin, string name, bool enable, DateTimeOffset? expires = null, string[]? scopes = null)
    {
        var current = server.Options.CurrentValue.Credentials.Single(c => c.Name == name);
        using var response = await api.PostAsync("rest/management/credentials", Caller.Session(admin), new
        {
            Name = name,
            AccessKey = "",
            Kind = "Token",
            Enable = enable,
            Scopes = scopes ?? current.Scopes.ToArray(),
            ExpiresUtc = expires
        });
        Assert.True(response.IsSuccessStatusCode, $"Saving '{name}' answered {(int)response.StatusCode}: {await response.Content.ReadAsStringAsync()}");
        await ServerFixture.EventuallyAsync(() =>
        {
            var now = server.Options.CurrentValue.Credentials.Single(c => c.Name == name);
            return now.Enable == enable && now.ExpiresUtc?.UtcDateTime.ToString("O") == expires?.UtcDateTime.ToString("O");
        }, "the saved token should have been reloaded");
    }
